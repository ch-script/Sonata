mod openrc;
mod systemd;

use std::fs;
use std::path::PathBuf;
use core_abs::sys::profile::SystemProfile;
use super::storage::{get_init_dir, get_workspace_path};
use super::model::InitWorkspace;
use std::process::Command;

fn generate_runner_script(name: &str) -> Result<PathBuf, String> {
    let path = get_workspace_path(name);
    if !path.exists() {
        return Err(format!("Workspace '{}' not found.", name));
    }

    let content = fs::read_to_string(&path).map_err(|e| e.to_string())?;
    let ws: InitWorkspace = toml::from_str(&content).map_err(|e| e.to_string())?;

    let run_dir = get_init_dir().join("run");
    fs::create_dir_all(&run_dir).map_err(|e| e.to_string())?;

    let script_path = run_dir.join(format!("{}.sh", name));
    let mut script_content = String::from("#!/usr/bin/env sh\n\n# Auto-generated by paw\n");
    for cmd in ws.commands {
        script_content.push_str(&format!("{}\n", cmd));
    }

    fs::write(&script_path, script_content).map_err(|e| e.to_string())?;

    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let mut perms = fs::metadata(&script_path).map_err(|e| e.to_string())?.permissions();
        perms.set_mode(0o755);
        fs::set_permissions(&script_path, perms).map_err(|e| e.to_string())?;
    }

    Ok(script_path)
}
pub fn run_wp(name: &str) -> Result<(), String> {
    let script_path = generate_runner_script(name)?;

    Command::new("sh")
        .arg(&script_path)
        .spawn()
        .map_err(|e| format!("Failed to execute script: {}", e))?;

    println!("[paw] Executing '{}'", name);
    Ok(())
}

pub fn activate(name: &str, profile: &SystemProfile) -> Result<(), String> {
    let script_path = generate_runner_script(name)?;

    match profile.init_system.as_str() {
        "passive" | "none" | "manual" => {
                    println!("[paw] Runner script generated at: {}", script_path.display());
                    Ok(())
                }
        "systemd" => systemd::activate(name, &script_path),
        "openrc" => openrc::activate(name, &script_path),
        _ => Err(format!("Init system '{}' not supported yet.", profile.init_system)),
    }
}

pub fn deactivate(name: &str, profile: &SystemProfile) -> Result<(), String> {
    match profile.init_system.as_str() {
        "systemd" => systemd::deactivate(name),
        "openrc" => openrc::deactivate(name),
        _ => Err("Deactivation not supported for this init system.".to_string()),
    }
}
